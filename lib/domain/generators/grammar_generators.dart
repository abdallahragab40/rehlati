T _focused<T>(List<T> pool, Rng r, String? focus, String Function(T) key) =>
    pool.where((x) => key(x) == focus).firstOrNull ?? r.sample<T>(pool);

/// ١ — اسم ولا فعل ولا حرف؟ الحروف من المستوى التالت.
Question arWordType(int lv, Rng r, {String? focus}) {
  final pool = lv <= 2 ? wordTypes.where((w) => w.$2 != 'حرف').toList() : wordTypes;
  final (word, type) = _focused(pool, r, focus, (w) => w.$1);
  return Question(
    type: 'ar_wordType', mode: QMode.choice, skill: 'wordType:$word', numeric: false,
    ask: 'الكلمة دي اسم ولا فعل ولا حرف؟',
    speak: 'الكلمة دي اسم ولا فعل ولا حرف؟',
    clips: [say('الكلمة دي اسم ولا فعل ولا حرف؟'), say(word)],
    visuals: [BigLetterVisual(word)],
    choices: const ['اسم', 'فعل', 'حرف'],
    answer: type,
    hint: 'الاسم: حاجة أو حد (كِتَاب، وَلَد). الفعل: حدث حصل أو بيحصل (كَتَبَ، يَلْعَبُ). '
        'الحرف: مالوش معنى غير مع كلمة تانية (فِي، مِنْ) ☝️',
    speakHint: 'الاسم حاجة أو حد، والفعل حدث، والحرف مالوش معنى لوحده',
    sayRight: word,
  );
}

/// ٢ — مفرد ولا مثنى ولا جمع؟
Question arNumber(int lv, Rng r, {String? focus}) {
  final set = _focused(numberForms, r, focus, (w) => w.$1);
  final forms = [(set.$1, 'مفرد'), (set.$2, 'مثنى'), (set.$3, 'جمع')];
  final (word, kind) = r.sample(forms);
  return Question(
    type: 'ar_number', mode: QMode.choice, skill: 'number:${set.$1}', numeric: false,
    ask: 'الكلمة دي مفرد ولا مثنى ولا جمع؟',
    speak: 'الكلمة دي مفرد ولا مثنى ولا جمع؟',
    clips: [say('الكلمة دي مفرد ولا مثنى ولا جمع؟'), say(word)],
    visuals: [BigLetterVisual(word)],
    choices: const ['مفرد', 'مثنى', 'جمع'],
    answer: kind,
    hint: 'المفرد واحد، والمثنى اتنين (آخره ـانِ زي وَلَدَانِ)، والجمع أكتر من اتنين ☝️',
    speakHint: 'المفرد واحد، والمثنى اتنين، والجمع أكتر من اتنين',
    sayRight: word,
  );
}

/// ٣ — مذكر ولا مؤنث؟
Question arGender(int lv, Rng r, {String? focus}) {
  final pair = _focused(genderPairs, r, focus, (w) => w.$1);
  final fem = r.chance(.5);
  final word = fem ? pair.$2 : pair.$1;
  return Question(
    type: 'ar_gender', mode: QMode.choice, skill: 'gender:${pair.$1}', numeric: false,
    ask: 'الكلمة دي مذكر ولا مؤنث؟',
    speak: 'الكلمة دي مذكر ولا مؤنث؟',
    clips: [say('الكلمة دي مذكر ولا مؤنث؟'), say(word)],
    visuals: [BigLetterVisual(word)],
    choices: const ['مذكر', 'مؤنث'],
    answer: fem ? 'مؤنث' : 'مذكر',
    hint: 'المؤنث غالبًا آخره تاء مربوطة (ـة)، وفيه كلمات مؤنثة من غيرها زي بِنْت وأُمّ ☝️',
    speakHint: 'المؤنث غالبا آخره تاء مربوطة',
    sayRight: word,
  );
}

/// ٤ — عكس الكلمة: الكلمة والطفل يختار عكسها من كلمات تانية من نفس القايمة.
Question arOpposite(int lv, Rng r, {String? focus}) {
  final pair = _focused(opposites, r, focus, (w) => w.$1);
  final flip = r.chance(.5);
  final (word, answer) = flip ? (pair.$2, pair.$1) : (pair.$1, pair.$2);
  final others = r.shuffle([
    for (final o in opposites)
      if (o != pair) r.chance(.5) ? o.$1 : o.$2,
  ]);
  return Question(
    type: 'ar_opposite', mode: QMode.choice, skill: 'opposite:${pair.$1}', numeric: false, bigChoices: true,
    ask: 'إيه عكس الكلمة دي؟',
    speak: 'إيه عكس الكلمة دي؟',
    clips: [say('إيه عكس الكلمة دي؟'), say(word)],
    visuals: [BigLetterVisual(word)],
    choices: r.shuffle([answer, ...others.take(lv <= 2 ? 2 : 3)]),
    answer: answer,
    hint: 'العكس معناه الضد: الكبير عكسه الصغير ☝️',
    speakHint: 'العكس معناه الضد',
    sayRight: answer,
  );
}

/// ٥ — كمّل الجملة: الكلمات التلاتة بنفس الإعراب، فالمعنى بس هو اللي بيحدد الصح.
Question arSentence(int lv, Rng r, {String? focus}) {
  final (sentence, answer, wrong) = _focused(blankSentences, r, focus, (s) => s.$1);
  return Question(
    type: 'ar_sentence', mode: QMode.choice, skill: 'sentence:$sentence', numeric: false, bigChoices: true,
    ask: 'اختار الكلمة اللي تكمّل الجملة',
    speak: 'اختار الكلمة اللي تكمّل الجملة',
    visuals: [WordLineVisual.text(sentence, big: true)],
    choices: r.shuffle([answer, ...wrong]),
    answer: answer,
    hint: 'اقرا الجملة بكل كلمة، واختار اللي معناها صح 📖',
    speakHint: 'اقرا الجملة بكل كلمة، واختار اللي معناها صح',
    sayRight: sentence.replaceFirst('_____', answer).replaceAll('.', '.'),
  );
}
