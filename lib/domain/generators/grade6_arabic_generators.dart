/// (الكلمة، نوع المعرفة أو «نكرة»).
const marifaWords = [
  ('كِتَابٌ', 'نكرة'), ('وَلَدٌ', 'نكرة'), ('مَدِينَةٌ', 'نكرة'), ('شَجَرَةٌ', 'نكرة'),
  ('هُوَ', 'ضمير'), ('نَحْنُ', 'ضمير'), ('أَنْتِ', 'ضمير'),
  ('مُحَمَّدٌ', 'علم'), ('مِصْرُ', 'علم'), ('سَارَةُ', 'علم'),
  ('هَذَا', 'اسم إشارة'), ('تِلْكَ', 'اسم إشارة'), ('هَؤُلَاءِ', 'اسم إشارة'),
  ('الَّذِي', 'اسم موصول'), ('الَّتِي', 'اسم موصول'),
  ('الْمَدْرَسَةُ', 'معرف بأل'), ('الْقَمَرُ', 'معرف بأل'), ('الْكِتَابُ', 'معرف بأل'),
];

/// نكرة ولا معرفة؟ ومن درس «أنواع المعارف» (أو المستوى الرابع): نوع المعرفة. focus: nakira / types.
Question arNakira(int lv, Rng r, {String? focus}) {
  final (word, kind) = r.sample(marifaWords);
  final types = focus == 'types' || (focus == null && lv >= 4 && kind != 'نكرة');
  if (types && kind != 'نكرة') {
    return _classify('ar_nakira', 'marifa:$kind', 'الكلمة دي معرفة من أنهي نوع؟', word,
        ['ضمير', 'علم', 'اسم إشارة', 'اسم موصول', 'معرف بأل'], kind, r,
        hint: 'المعارف: الضمير (هو)، العلم (محمد)، اسم الإشارة (هذا)، الاسم الموصول (الذي)، والمعرف بأل (الكتاب) ☝️',
        speakHint: 'المعارف: الضمير، والعلم، واسم الإشارة، والاسم الموصول، والمعرف بأل');
  }
  return _classify('ar_nakira', 'nakira:${kind == 'نكرة'}', 'الكلمة دي نكرة ولا معرفة؟', word, ['نكرة', 'معرفة'],
      kind == 'نكرة' ? 'نكرة' : 'معرفة', r,
      hint: 'النكرة اسم مش محدد (كِتَابٌ)، والمعرفة اسم محدد (الْكِتَابُ، مُحَمَّدٌ، هُوَ) ☝️',
      speakHint: 'النكرة اسم مش محدد، والمعرفة اسم محدد');
}

