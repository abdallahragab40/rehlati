/// focus: alif / yaa / waw / line.
Question arHamzaMid(int lv, Rng r, {String? focus}) {
  final pool = hamzaMidWords.where((w) => w.$5 == focus).toList();
  final (before, after, full, hamza, kind) = r.sample(pool.isEmpty ? hamzaMidWords : pool);
  const ask = 'الهمزة في وسط الكلمة بتتكتب إزاي؟';
  return Question(
    type: 'ar_hamzaMid', mode: QMode.choice, skill: 'hamzaMid:$kind', numeric: false, bigChoices: true,
    ask: ask, speak: '$ask $full', clips: [say(ask), say(full)],
    visuals: [BigLetterVisual('$before _ $after')],
    choices: r.shuffle(['أ', 'ئ', 'ؤ', 'ء']), answer: hamza,
    choiceSay: const {'أ': 'على الألف', 'ئ': 'على الياء', 'ؤ': 'على الواو', 'ء': 'على السطر'},
    hint: 'قارن حركة الهمزة بحركة اللي قبلها وخد الأقوى: الكسرة ← ئ، الضمة ← ؤ، الفتحة ← أ. وبعد ألف ساكنة وفتحتها الهمزة بتتكتب على السطر ☝️',
    speakHint: 'خد الحركة الأقوى: الكسرة ثم الضمة ثم الفتحة',
    sayRight: full,
  );
}

