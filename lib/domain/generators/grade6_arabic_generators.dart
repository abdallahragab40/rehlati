/// (قبل الهمزة، بعدها، الكلمة مشكولة، الهمزة، مكانها) — alif / yaa / waw / line.
const hamzaMidWords = [
  ('س', 'ل', 'سَأَلَ', 'أ', 'alif'), ('ر', 'س', 'رَأْسٌ', 'أ', 'alif'), ('ف', 'ر', 'فَأْرٌ', 'أ', 'alif'), ('ي', 'كل', 'يَأْكُلُ', 'أ', 'alif'),
  ('ب', 'ر', 'بِئْرٌ', 'ئ', 'yaa'), ('ذ', 'ب', 'ذِئْبٌ', 'ئ', 'yaa'), ('ر', 'ة', 'رِئَةٌ', 'ئ', 'yaa'), ('مسا', 'ل', 'مَسَائِلُ', 'ئ', 'yaa'),
  ('م', 'من', 'مُؤْمِنٌ', 'ؤ', 'waw'), ('س', 'ال', 'سُؤَالٌ', 'ؤ', 'waw'), ('ف', 'اد', 'فُؤَادٌ', 'ؤ', 'waw'), ('ي', 'دي', 'يُؤَدِّي', 'ؤ', 'waw'),
  ('تسا', 'ل', 'تَسَاءَلَ', 'ء', 'line'), ('قرا', 'ة', 'قِرَاءَةٌ', 'ء', 'line'), ('مرو', 'ة', 'مُرُوءَةٌ', 'ء', 'line'),
