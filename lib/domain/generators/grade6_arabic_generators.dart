/// focus: raf / jazm / five / illa.
Question arMudari(int lv, Rng r, {String? focus}) {
  if (focus == 'illa' || (focus == null && r.chance(.25))) {
    final (verb, illa) = r.sample(illaVerbs);
    return _classify('ar_mudari', 'mudari:illa', 'الفعل ده صحيح الآخر ولا معتل الآخر؟', verb,
        ['صحيح الآخر', 'معتل الآخر'], illa ? 'معتل الآخر' : 'صحيح الآخر', r,
        hint: 'المعتل الآخر آخره حرف علة (ا، و، ي): يَدْعُو، يَرْمِي، يَسْعَى ☝️', speakHint: 'المعتل الآخر آخره حرف علة');
  }
  final pool = mudariSentences.where((s) => s.$4 == focus).toList();
  final (sentence, answer, choices, kind) = r.sample(pool.isEmpty ? mudariSentences : pool);
  return _blank('ar_mudari', 'mudari:$kind', 'اختار الفعل المضارع بالشكل الصح', sentence, answer, choices, r,
      hint: switch (kind) {
        'jazm' => 'بعد لَمْ المضارع بيتجزم بالسكون: لَمْ يَلْعَبْ ☝️',
        'five' => 'الأفعال الخمسة بتترفع بثبوت النون، وبتتجزم بحذفها: لَمْ يَكْتُبُوا ☝️',
        _ => 'المضارع من غير ناصب ولا جازم بيبقى مرفوع بالضمة ☝️',
      },
      speakHint: 'بص على اللي قبل الفعل: فيه جازم ولا لأ');
}
