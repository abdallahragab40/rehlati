/// الحروف اللي مابتتوصلش باللي بعدها: ليها شكلين بس (منفصل وآخر الكلمة).
const nonJoining = {'ا', 'أ', 'د', 'ذ', 'ر', 'ز', 'و'};

/// شكل الحرف في أول الكلمة ووسطها وآخرها بالكشيدة (ـ). الحرف اللي مابيتوصلش أوله زي منفصله.
String letterForm(String l, String pos) {
  final joins = !nonJoining.contains(l);
  return switch (pos) {
    'first' => joins ? '$lـ' : l,
    'middle' => joins ? 'ـ$lـ' : 'ـ$l',
    _ => 'ـ$l',
  };
}

