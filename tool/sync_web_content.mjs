// يحوّل ملفات المحتوى في نسخة الويب لـ Dart — عشان أي تحديث في المحتوى يتنقل من غير نسخ يدوي.
//
//   node tool/sync_web_content.mjs [path/to/rehlati-web]
//
// بيكتب:
//   lib/content/madd_data.g.dart          ← data/madd.js
//   lib/content/parent_guide_data.g.dart  ← data/parent-1.js, parent-2.js, parent-3.js
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const web = path.resolve(process.argv[2] ?? '../rehlati-web');
const out = path.resolve('lib/content');

function load(files) {
  const ctx = {};
  vm.createContext(ctx);
  for (const f of files) {
    // const على مستوى الملف مش بتبقى خاصية في الـ context — نحوّلها var
    const src = fs.readFileSync(path.join(web, f), 'utf8').replace(/^const /gm, 'var ');
    vm.runInContext(src, ctx, {filename: f});
  }
  return ctx;
}

// نص Dart: JSON صالح كنص Dart بعلامات تنصيص مزدوجة، بس $ لازم يتهرّب
const s = v => JSON.stringify(String(v)).replace(/\$/g, '\\$');
const list = (a, f = s) => `[${a.map(f).join(', ')}]`;
const header = src => `// GENERATED by tool/sync_web_content.mjs from rehlati-web/${src} — do not edit.
// ignore_for_file: prefer_single_quotes, lines_longer_than_80_chars
`;

// ---------------------------------------------------------------- المدود
{
  const c = load(['data/madd.js']);
  const types = c.MADD_TYPES.map(t => `  MaddType(
    key: ${s(t.key)}, name: ${s(t.name)}, box: ${s(t.box)},
    baseLetter: ${s(t.baseLetter)}, maddLetter: ${s(t.maddLetter)}, result: ${s(t.result)},
    harakaName: ${s(t.harakaName)}, harakaWord: ${s(t.harakaWord)}, harakaMark: ${s(t.harakaMark)},
    letterName: ${s(t.letterName)}, letterWord: ${s(t.letterWord)}, rule: ${s(t.rule)},
    examples: ${list(t.examples)},
  ),`).join('\n');
  const words = c.MADD_WORDS.map(w =>
    `  MaddWord(plain: ${s(w.plain)}, w: ${s(w.w)}, type: ${s(w.type)}, madd: ${s(w.madd)}, parts: ${list(w.parts)}, e: ${s(w.e)}, pic: ${!!w.pic}, lvl: ${w.lvl}),`
  ).join('\n');
  const say = Object.entries(c.MADD_SAY || {}).map(([k, v]) => `  ${s(k)}: ${s(v)},`).join('\n');
  fs.writeFileSync(path.join(out, 'madd_data.g.dart'), `${header('data/madd.js')}
import 'madd.dart';

const maddTypes = <MaddType>[
${types}
];

const maddWords = <MaddWord>[
${words}
];

/// لو المقطع محتاج نطق مختلف عن شكله المكتوب.
const maddSay = <String, String>{
${say}
};

/// حروف إضافية للاختيارات الخاطئة في أسئلة «الممدود» (مش حروف مد).
const maddDistractors = ${list(c.MADD_DISTRACTORS || [])};
`);
  console.log(`madd: ${c.MADD_TYPES.length} types, ${c.MADD_WORDS.length} words`);
}

// ---------------------------------------------------------------- دليل ولي الأمر
{
  const c = load(['data/parent-1.js', 'data/parent-2.js', 'data/parent-3.js']);
  const b = c.PG_DATA.map(x => `  PgBehavior(
    id: ${s(x.id)}, icon: ${s(x.icon)}, title: ${s(x.title)}, cat: ${s(x.cat)},${x.alt ? ` alt: ${s(x.alt)},` : ''}
    tags: ${list(x.tags)},
    what: ${s(x.what)},
    why: ${list(x.why)},
    steps: [${x.steps.map(st => `PgStep(${s(st.t)}${st.say ? `, say: ${s(st.say)}` : ''})`).join(', ')}],
    phrases: ${list(x.phrases)},
    avoid: ${list(x.avoid)},
    teach: [${x.teach.map(t => `(${s(t[0])}, ${s(t[1])})`).join(', ')}],
    calm: ${list(x.calm)},${x.calmSay ? `\n    calmSay: ${s(x.calmSay)},` : ''}${x.help ? `\n    help: ${s(x.help)},` : ''}${x.game ? `
    game: PgGame(${s(x.game.q)}, [${x.game.opts.map(o => `(${s(o[0])}, ${!!o[1]})`).join(', ')}], ${s(x.game.ok)}),` : ''}
  ),`).join('\n');
  const cats = c.PG_CATEGORIES.map(x => `  PgCategory(${s(x.id)}, ${s(x.icon)}, ${s(x.name)}),`).join('\n');
  const goals = Object.entries(c.PG_GOALS).map(([k, v]) => `  ${s(k)}: ${s(v)},`).join('\n');
  fs.writeFileSync(path.join(out, 'parent_guide_data.g.dart'), `${header('data/parent-*.js')}
import 'parent_guide.dart';

const pgBehaviors = <PgBehavior>[
${b}
];

const pgCategories = <PgCategory>[
${cats}
];

/// ترتيب البطاقات في الصفحة الرئيسية (الأهم أولًا).
const pgFeatured = ${list(c.PG_FEATURED)};

/// نص "متى أحتاج لاستشارة مختص؟" المشترك.
const pgHelpBase = ${s(c.PG_HELP_BASE)};

/// اسم الهدف المختصر (للوحة ولي الأمر).
const pgGoals = <String, String>{
${goals}
};
`);
  console.log(`parent guide: ${c.PG_DATA.length} behaviors, ${c.PG_CATEGORIES.length} categories`);
}
