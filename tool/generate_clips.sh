#!/usr/bin/env bash
# يولّد مقاطع صوتية مؤقتة من tool/clips.tsv بصوت macOS العربي (Majed).
#
# ده بديل مؤقت لحد ما تتسجّل الأصوات الحقيقية. أصوات النظام في macOS مسموح
# استخدامها للتطوير الشخصي بس — لازم تتبدّل بتسجيل بشري أو صوت مرخّص قبل النشر.
#
# لتبديل مقطع بتسجيل حقيقي: حط ملف assets/audio/clips/<key>.m4a واشطب السطر من
# clips.tsv أو شغّل السكربت بـ KEEP_EXISTING=1 عشان مايكتبش فوق الملفات الموجودة.
set -euo pipefail
cd "$(dirname "$0")/.."

VOICE="${VOICE:-Majed}"
RATE="${RATE:-150}"
OUT=assets/audio/clips
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT"

keys=()
while IFS=$'\t' read -r key text; do
  [[ -z "$key" || "$key" == \#* ]] && continue
  keys+=("$key")
  if [[ "${KEEP_EXISTING:-0}" == 1 && -f "$OUT/$key.m4a" ]]; then continue; fi
  say -v "$VOICE" -r "$RATE" -o "$TMP/$key.aiff" "$text"
  afconvert -f m4af -d aac -b 64000 "$TMP/$key.aiff" "$OUT/$key.m4a"
done < tool/clips.tsv

# الملف ده بيقول للتطبيق أنهي مقاطع موجودة (زي audio/manifest.js في الويب)
{
  echo '// GENERATED by tool/generate_clips.sh — do not edit.'
  echo 'const clipKeys = <String>{'
  for k in "${keys[@]}"; do [[ -f "$OUT/$k.m4a" ]] && echo "  '$k',"; done
  echo '};'
} > lib/core/audio/clip_manifest.g.dart

echo "generated ${#keys[@]} clips into $OUT"
